package com.spotpulse;

import com.spotpulse.model.*;
import com.spotpulse.premium.*;
import org.hibernate.SessionFactory;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import java.nio.file.Path;
import java.sql.DriverManager;
import static org.assertj.core.api.Assertions.assertThat;

class PremiumPersistenceTests {
    @TempDir Path directory;

    SessionFactory open(String url) {
        return new Configuration().addAnnotatedClass(Space.class).addAnnotatedClass(Room.class)
                .addAnnotatedClass(User.class).addAnnotatedClass(Booking.class).addAnnotatedClass(FeatureFlag.class)
                .setProperty("hibernate.connection.url", url).setProperty("hibernate.connection.username", "sa")
                .setProperty("hibernate.connection.password", "").setProperty("hibernate.connection.driver_class", "org.h2.Driver")
                .setProperty("hibernate.hbm2ddl.auto", "update").buildSessionFactory();
    }

    @Test void upgradesLegacyRowsWithoutDeletingThemAndPersistsEntitlementAndFlagAcrossDatabaseReopen() throws Exception {
        String url = "jdbc:h2:file:" + directory.resolve("b6-restart").toAbsolutePath().toString().replace('\\', '/');
        // A pre-B6 database has no premium column. This database exists only in JUnit's temporary directory.
        try (var connection = DriverManager.getConnection(url, "sa", ""); var sql = connection.createStatement()) {
            sql.execute("create table spaces (id bigint generated by default as identity primary key, name varchar(255) not null, address varchar(255) not null, city varchar(255) not null)");
            sql.execute("insert into spaces (name,address,city) values ('Legacy Hub','Street 1','Kyiv')");
        }
        try (var factory = open(url); var session = factory.openSession()) {
            var transaction = session.beginTransaction();
            var legacy = session.find(Space.class, 1L);
            assertThat(legacy.isPremium()).isFalse();
            legacy.setPremium(true);
            session.persist(new FeatureFlag(FeatureKey.PREMIUM_FEATURES_ENABLED, true));
            transaction.commit();
        }
        // Closing every connection and rebuilding Hibernate simulates the persistence boundary of a restart.
        try (var factory = open(url); var session = factory.openSession()) {
            assertThat(session.find(Space.class, 1L).isPremium()).isTrue();
            assertThat(session.find(FeatureFlag.class, FeatureKey.PREMIUM_FEATURES_ENABLED).isEnabled()).isTrue();
            assertThat(session.createQuery("select count(s) from Space s", Long.class).getSingleResult()).isEqualTo(1);
        }
    }
}

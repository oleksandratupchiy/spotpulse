import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Reproducible, licensed UI assets for both renderers. No downloads or app data.
const frontend = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = resolve(frontend, 'node_modules');
const assets = resolve(frontend, '../spotpulse-backend/src/main/resources/static');
async function copy(source, target) {
  const destination = resolve(assets, target);
  await mkdir(dirname(destination), { recursive: true });
  await copyFile(resolve(modules, source), destination);
}
const faces = [];
for (const [name, family] of [['space-grotesk', 'Space Grotesk'], ['manrope', 'Manrope']]) {
  const packagePath = `@fontsource-variable/${name}`;
  const css = await readFile(resolve(modules, packagePath, 'index.css'), 'utf8');
  for (const face of css.match(/@font-face\s*\{[^}]+\}/g)) {
    const filename = face.match(/files\/([^\)]+)/)[1];
    if (!['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'].some(subset => filename.includes(`-${subset}-`))) continue;
    await copy(`${packagePath}/files/${filename}`, `css/fonts/${filename}`);
    faces.push(face.replace(`${family} Variable`, family).replace('./files/', './fonts/'));
  }
  await copy(`${packagePath}/LICENSE`, `css/fonts/${name}-OFL.txt`);
}
await writeFile(resolve(assets, 'css/fonts.css'), '/* Generated by npm run assets:sync. SIL OFL licenses in ./fonts/. */\n' + faces.join('\n') + '\n');
for (const [source, target] of [
  ['bootstrap/dist/css/bootstrap.min.css', 'css/vendor/bootstrap/bootstrap.min.css'],
  ['bootstrap/dist/js/bootstrap.bundle.min.js', 'js/vendor/bootstrap/bootstrap.bundle.min.js'],
  ['bootstrap/LICENSE', 'css/vendor/bootstrap/LICENSE.txt'],
  ['bootstrap-icons/font/bootstrap-icons.min.css', 'css/vendor/bootstrap-icons/bootstrap-icons.min.css'],
  ['bootstrap-icons/font/fonts/bootstrap-icons.woff2', 'css/vendor/bootstrap-icons/fonts/bootstrap-icons.woff2'],
  ['bootstrap-icons/font/fonts/bootstrap-icons.woff', 'css/vendor/bootstrap-icons/fonts/bootstrap-icons.woff'],
  ['bootstrap-icons/LICENSE', 'css/vendor/bootstrap-icons/LICENSE.txt'],
  ['jquery/dist/jquery.min.js', 'js/vendor/jquery/jquery.min.js'],
  ['jquery/LICENSE.txt', 'js/vendor/jquery/LICENSE.txt'],
]) await copy(source, target);
console.log('Shared fonts and server UI assets synchronized with installed packages.');
